from pydantic import BaseModel, Field

from open_fin_gym.pipeline.config import Scope


def build_paper_summary_prompt(
    scope: Scope,
) -> str:
    return f"""
You are designing a machine learning {scope.task_params.name} assessment based on the experiment(s) described in a science paper.

You should use the experiments described in the paper as a basis for designing a machine learning task. For
example if the paper assesses the performance of a machine learning model then you should model your task around the
experiments used in the assessment.

You should produce a detailed, unambiguous set of instructions to implement the task. This specification of the task
should consist of:

- A detailed plan of how the task should be implemented
- A set of instructions that will be provided to the user taking the task
- A detailed description of any training input datasets provided to the user
- A detailed description of any training target/ground-truth datasets provided to the user
- A detailed description of any test input datasets provided to the user
- A detailed description of the test output that should be generated by the user for final assessment
- A detailed description of any test target/ground-truth data
- A detailed description of the assessment of the task, i.e. what metrics should be used, and how they are applied to the datasets

This plan will then be used by downstream tasks to generate description files, and code to generate relevant datasets and
perform assessment. As such it should contain sufficient unambiguous detail required to implement the task.

{scope.task_params.example}

## Notes

- You can use the available tools to search github, and public financial data sources
- The plan you produce will be used by downstream tasks to define the task, and write code to
  retrieve and save the datasets and assess the task. As such your description should include as much detail as possible
  to recreate the experiment in the paper. The downstream tasks will not have access to the original paper, so should
  be able to implement the task without reference to the paper.
- If the papers contain multiple experiments, select one task to implement.
- When the task is run the user will be provided with the task description, training inputs, training target, and test input
  datasets (holding out the assessment test target data). The user will write their output to a file, which will then be read
  and assessed using the task metrics.
- The dataset descriptions should be sufficiently detailed to allow a user to write a script to retrieve/download the data
  from public sources. Where possible use direct links found in the paper itself, or free public data sources such as Yahoo finance.
- If the data in the paper is not publicly available then you may create a plan that recreates the experiment from public data
  sources.
- Any parameters required to sample data should specified (e.g. date-ranges, periodicity)
- The following data sources are recommended (either public or API keys will be provided);
  - Public git repositories
  - Any datasets with public download links
  - Yahoo finance
  - Kaggle (API key provided)
  - Alpaca (API credential provided)
""".strip()


class Dataset(BaseModel):
    name: str = Field(description="ID of the dataset")
    filename: str = Field(description="Filename used to store the datasets")
    description: str = Field(
        description="Description of the dataset including its structure and how it is constructed"
    )
    source: str = Field(description="Where the data was sourced from")
    relevant_urls: list[str] = Field(
        description="URLs related to the dataset, e.g. download links"
    )
    download_link: str | None = Field(
        description="Optional dataset direct download link if available"
    )


class AssessmentMetric(BaseModel):
    name: str = Field(description="Name id assigned to the metric")
    description: str = Field(
        description="Description of the metric and how it applied to the users output"
    )
    input_datasets: list[str] = Field(
        description="List of dataset filenames that form the input to the metric"
    )


class PaperTaskSpecification(BaseModel):
    reasoning: str
    task_name: str = Field(description="Name id assigned to the task")
    task_implementation_plan: str = Field(
        description=(
            "Outline of how the task should be implemented by downstream tasks"
        )
    )
    task_instructions: str = Field(
        description="Task instructions that will be provided to the user"
    )
    training_inputs: list[Dataset] = Field(
        description="List of training input datasets"
    )
    training_targets: list[Dataset] = Field(
        description="List of training ground-truth/target datasets"
    )
    test_inputs: list[Dataset] = Field(description="List of test input datasets")
    test_targets: list[Dataset] = Field(
        description="List of ground truth datasets used to assess the users output against"
    )
    test_outputs: list[Dataset] = Field(
        description="List of test outputs files the user should produce"
    )
    assessment_metrics: list[AssessmentMetric] = Field(
        description="List of metrics used to assess the users output"
    )
